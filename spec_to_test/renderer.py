class UnityTestRenderer:
    """Render the supported Gate 4 templates into the Unity fixture project."""

    def __init__(self, unity_project: Path) -> None:
        self.unity_project = unity_project
        self.assets = unity_project / "Assets"
        self.editmode_dir = self.assets / "Tests" / "EditMode"
        self.playmode_dir = self.assets / "Tests" / "PlayMode"

    def render(self, plan: TestPlanIR) -> Dict[str, Path]:
        self._validate_plan(plan)
        self.editmode_dir.mkdir(parents=True, exist_ok=True)
        self.playmode_dir.mkdir(parents=True, exist_ok=True)

        outputs = {
            "editmode_asmdef": self.editmode_dir / "GameTestFixture.EditModeTests.asmdef",
            "editmode_test": self.editmode_dir / "GeneratedCheckpointRequirementEditModeTest.cs",
            "playmode_test": self.playmode_dir / "GeneratedCheckpointRequirementPlayModeTest.cs",
        }
        outputs["editmode_asmdef"].write_text(EDITMODE_ASMDEF, encoding="utf-8")
        outputs["editmode_test"].write_text(EDITMODE_TEST, encoding="utf-8")
        outputs["playmode_test"].write_text(PLAYMODE_TEST, encoding="utf-8")
        return outputs

    @staticmethod
    def _validate_plan(plan: TestPlanIR) -> None:
        templates = {case.template for case in plan.cases}
        required = {
            "checkpoint_state_persistence_unit",
            "checkpoint_respawn_extraction_playmode",
        }
        missing = sorted(required - templates)
        if missing:
            raise ValueError(f"Test Plan IR missing required templates: {', '.join(missing)}")
